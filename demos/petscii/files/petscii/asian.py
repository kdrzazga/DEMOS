    def paste_mouth(self, rows):
        column, row = self.mouth_area[0] - 1, self.mouth_area[1] - 1
        for delta_row, line in enumerate(rows):
            for delta_column, code in enumerate(line):
                self.chars[row + delta_row][column + delta_column] = code
                self.reversed[row + delta_row][column + delta_column] = 1

